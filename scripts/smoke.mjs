import assert from 'node:assert/strict';
import { pathToFileURL } from 'node:url';
import { resolve } from 'node:path';
const worker = (await import(pathToFileURL(resolve('dist/server/index.js')).href)).default;
const catalogResponse = await worker.fetch(new Request('https://local.example/api/catalog'));
assert.equal(catalogResponse.status, 200, 'Catalog endpoint should load the public spreadsheet');
const catalog = await catalogResponse.json();
console.log(`Source response: ${catalog.watches.length} watches; failed: ${catalog.failedBrands.join(', ') || 'none'}; brands: ${catalog.brands.length}; images: ${catalog.watches.filter((watch) => watch.image).length}`);
console.log(catalog.brands.map((brand) => `${brand.name}:${brand.count}`).join(' '));
console.log(`Duplicate IDs: ${catalog.duplicateIds.length}`);
assert.ok(catalog.watches.length >= 600, `Expected the real catalog, got ${catalog.watches.length} watches`);
assert.ok(catalog.brands.length >= 21, `Expected 21 brand tabs, got ${catalog.brands.length}`);
assert.ok(catalog.watches.filter((watch) => watch.image).length >= 300, 'Embedded watch images were not loaded');
assert.equal(catalog.watches.find((watch) => watch.id === 'RLX-W001')?.price, 5950);
assert.equal(catalog.watches.find((watch) => watch.id === 'RLX-W001')?.stock, 10);
const detail = await worker.fetch(new Request('https://local.example/watch/RLX-W001'));
assert.equal(detail.status, 200);
const html = await detail.text();
assert.match(html, /Rolex Datejust/);
assert.match(html, /og:image/);
const imageResponse = await worker.fetch(new Request('https://local.example/image/RLX-W001'));
assert.equal(imageResponse.status, 200, 'Embedded watch image proxy should load');
assert.match(imageResponse.headers.get('content-type') || '', /^image\//);
console.log(`Live source smoke passed: ${catalog.watches.length} watches, ${catalog.watches.filter((watch) => watch.image).length} images, ${catalog.brands.length} brand tabs.`);
if (catalog.failedBrands.length || catalog.duplicateIds.length) console.log(`Warnings: failed brands ${catalog.failedBrands.join(', ') || 'none'}; duplicate IDs ${catalog.duplicateIds.join(', ') || 'none'}`);
