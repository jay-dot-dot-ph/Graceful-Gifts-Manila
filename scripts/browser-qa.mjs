import assert from 'node:assert/strict';
import { chromium } from 'playwright-core';
import { mkdirSync } from 'node:fs';
import { resolve } from 'node:path';

const edge = 'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe';
const base = process.argv[2] || process.env.QA_BASE || 'http://127.0.0.1:4173';
const catalogEndpoint = process.argv[3] || process.env.QA_CATALOG_URL || '/api/catalog';
const output = resolve('.sites-runtime');
mkdirSync(output, { recursive: true });
const browser = await chromium.launch({ executablePath: edge, headless: true });
const errors = [];
try {
  const desktop = await browser.newContext({ viewport: { width: 1440, height: 1000 }, permissions: ['clipboard-read', 'clipboard-write'] });
  const page = await desktop.newPage();
  page.on('pageerror', (error) => errors.push(error.message));
  await page.goto(base + '/', { waitUntil: 'domcontentloaded' });
  await page.locator('.hero h1').waitFor({ timeout: 30000 });
  await page.waitForFunction(() => { const img = document.querySelector('.hero-visual img'); return img && img.complete && img.naturalWidth > 0; }, null, { timeout: 20000 });
  assert.equal(await page.locator('.hero-visual img').evaluate((img) => img.complete && img.naturalWidth > 0), true, 'Hero watch image should load');
  await page.screenshot({ path: resolve(output, 'qa-desktop.png') });
  await page.goto(base + '/watches');
  await page.locator('.watch-card').first().waitFor({ timeout: 30000 });
  const allCount = await page.locator('#result-count').innerText();
  assert.match(allCount, /696 watches/);
  await page.locator('#catalog-search').fill('RLX-W001');
  assert.match(await page.locator('#result-count').innerText(), /1 watch/);
  await page.goto(base + '/watches/rolex');
  await page.locator('.watch-card').first().waitFor({ timeout: 30000 });
  assert.match(await page.locator('#result-count').innerText(), /127 watches/);
  await page.goto(base + '/watches');
  await page.locator('.watch-card').first().waitFor({ timeout: 30000 });
  const liveCatalog = await page.evaluate(async (endpoint) => (await fetch(endpoint)).json(), catalogEndpoint);
  const realSoldOut = liveCatalog.watches.find((watch) => watch.stock === 0);
  const soldOut = realSoldOut || liveCatalog.watches.find((watch) => watch.id !== 'RLX-W001');
  assert.ok(soldOut, 'Catalog should include a watch for the sold-out journey');
  if (!realSoldOut) {
    const fixtureCatalog = structuredClone(liveCatalog);
    fixtureCatalog.watches.find((watch) => watch.id === soldOut.id).stock = 0;
    await page.route('**' + catalogEndpoint, (route) => route.fulfill({ json: fixtureCatalog }));
    await page.reload();
    await page.locator('.watch-card').first().waitFor({ timeout: 30000 });
  }
  await page.locator('[data-filter="availability"]').selectOption('soldout');
  assert.ok(Number((await page.locator('#result-count').innerText()).split(' ')[0]) > 0);
  assert.match(await page.locator('.watch-card').first().innerText(), /Sold out/i);
  await page.locator('[data-clear]').first().click();
  await page.locator('#catalog-sort').selectOption('price-asc');
  const firstPrices = await page.locator('.watch-card .card-bottom strong').allInnerTexts();
  const numericPrices = firstPrices.slice(0, 2).map((value) => Number(value.replace(/[^\d.]/g, '')));
  assert.ok(numericPrices[0] <= numericPrices[1], 'Price sorting should be ascending');
  await page.goto(base + '/watch/RLX-W001');
  await page.locator('.detail-copy h1').waitFor({ timeout: 30000 });
  assert.match(await page.locator('.detail-copy h1').innerText(), /Datejust/i);
  await page.locator('.inquiry-button').click();
  await page.locator('.inquiry-button.copied').waitFor({ timeout: 5000 });
  assert.match(await page.locator('.inquiry-button').innerText(), /MESSAGE COPIED/i);
  const message = await page.evaluate(() => navigator.clipboard.readText());
  assert.match(message, /Watch ID: RLX-W001/);
  assert.match(message, /₱5,950/);
  assert.match(message, /\/watch\/RLX-W001/);
  await page.evaluate(() => { window.open = (url) => { window.__lastMessengerUrl = url; }; });
  await page.locator('.inquiry-button').click();
  assert.equal(await page.evaluate(() => window.__lastMessengerUrl), 'https://m.me/GracefulGifts.Manila');
  await page.locator('.favorite-detail').click();
  await page.goto(base + '/favorites');
  await page.locator('.favorite-row').waitFor({ timeout: 30000 });
  await page.reload();
  await page.locator('.favorite-row').waitFor({ timeout: 30000 });
  await page.locator('[data-select]').check();
  assert.equal(await page.locator('[data-inquire-selected]').isEnabled(), true);
  await page.locator('[data-inquire-selected]').click();
  await page.locator('[data-inquire-selected].copied').waitFor({ timeout: 5000 });
  assert.match(await page.evaluate(() => navigator.clipboard.readText()), /RLX-W001/);
  await page.goto(`${base}/watch/${soldOut.id}`);
  await page.locator('.detail-copy h1').waitFor({ timeout: 30000 });
  assert.match(await page.locator('.detail-stock').innerText(), /Sold out/i);
  await page.locator('.inquiry-button').click();
  await page.locator('.inquiry-button.copied').waitFor({ timeout: 5000 });
  assert.match(await page.evaluate(() => navigator.clipboard.readText()), /currently sold out/);
  await page.goto(base + '/contact');
  await page.locator('.contact-method').first().waitFor({ timeout: 30000 });
  assert.equal(await page.locator('a[href="tel:+639773847543"]').count() > 0, true);
  assert.equal(await page.locator('a[href="viber://chat?number=%2B639773847543"]').count() > 0, true);
  await desktop.close();

  const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  const mobilePage = await mobile.newPage();
  mobilePage.on('pageerror', (error) => errors.push(error.message));
  await mobilePage.goto(base + '/', { waitUntil: 'domcontentloaded' });
  await mobilePage.locator('.hero h1').waitFor({ timeout: 30000 });
  const size = await mobilePage.evaluate(() => ({ viewport: innerWidth, content: document.documentElement.scrollWidth }));
  assert.ok(size.content <= size.viewport + 1, `Mobile overflow: ${JSON.stringify(size)}`);
  await mobilePage.screenshot({ path: resolve(output, 'qa-mobile.png') });
  await mobilePage.locator('[data-menu]').click();
  assert.equal(await mobilePage.locator('#mobile-nav').isVisible(), true);
  await mobilePage.goto(base + '/watch/RLX-W001');
  await mobilePage.locator('.mobile-inquiry-bar').waitFor({ timeout: 30000 });
  assert.equal(await mobilePage.locator('.mobile-inquiry-bar').isVisible(), true);
  await mobile.close();
  assert.deepEqual(errors, [], 'No browser JavaScript errors expected');
  console.log(`Browser QA passed: desktop catalog/search/filter/sort/favorites/inquiry, mobile layout/navigation/detail action; sold-out journey used ${realSoldOut ? 'live stock' : 'a clearly labeled test fixture'}.`);
} finally {
  await browser.close();
}
