import assert from 'node:assert/strict';
import { chromium } from 'playwright-core';
import { mkdirSync } from 'node:fs';
import { resolve } from 'node:path';

const executablePath = process.env.PLAYWRIGHT_EXECUTABLE_PATH
  || (process.platform === 'win32' ? 'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe' : undefined);
const base = process.argv[2] || process.env.QA_BASE || 'http://127.0.0.1:4173';
const catalogEndpoint = process.argv[3] || process.env.QA_CATALOG_URL || '/api/catalog.json';
const output = resolve('.sites-runtime');
mkdirSync(output, { recursive: true });
const browser = await chromium.launch({ ...(executablePath ? { executablePath } : {}), headless: true });
const errors = [];
try {
  const desktop = await browser.newContext({ viewport: { width: 1440, height: 1000 }, permissions: ['clipboard-read', 'clipboard-write'] });
  const page = await desktop.newPage();
  page.on('pageerror', (error) => errors.push(error.message));
  await page.goto(base + '/', { waitUntil: 'domcontentloaded' });
  await page.locator('.hero h1').waitFor({ timeout: 30000 });
  await page.waitForFunction(() => { const img = document.querySelector('.hero-visual img'); return img && img.complete && img.naturalWidth > 0; }, null, { timeout: 20000 });
  assert.equal(await page.locator('.hero-visual img').evaluate((img) => img.complete && img.naturalWidth > 0), true, 'Hero watch image should load');
  assert.match(await page.locator('.trust-banner').innerText(), /Cash on Delivery Nationwide[\s\S]*Inspect Before Paying[\s\S]*Forbes Commercial/);
  assert.equal(await page.locator('.floating-chat').getAttribute('data-open-chat'), '');
  assert.equal(await page.locator('.card-inquire, .watch-modal').count(), 0, 'Card inquiry and specs modal are removed');
  await page.screenshot({ path: resolve(output, 'qa-desktop.png') });
  await page.locator('.desktop-nav a[href="/brands"]').click();
  await page.locator('.brands-page-content .brand-tile').first().waitFor({ timeout: 30000 });
  assert.equal(new URL(page.url()).pathname, '/brands', 'Brands has its own URL');
  assert.equal(await page.locator('.desktop-nav a[href="/brands"]').getAttribute('aria-current'), 'page');
  assert.ok(await page.locator('.brands-page-content .brand-tile').count() >= 20, 'Brands page lists populated brands');
  assert.equal(await page.locator('#catalog-search').count(), 0, 'Brands page is distinct from the watch catalog');
  await page.locator('.brands-page-content a[href="/watches/vacheron"]').click();
  await page.locator('.watch-card').first().waitFor({ timeout: 30000 });
  assert.equal(new URL(page.url()).pathname, '/watches/vacheron', 'Brand tile opens its watches');
  assert.equal(await page.locator('.brand-list-section, [data-brand-toggle]').count(), 0, 'Brand watch pages omit the redundant brand strip');
  await page.goto(base + '/watches');
  await page.locator('.watch-card').first().waitFor({ timeout: 30000 });
  assert.equal(await page.locator('.brand-list-section, [data-brand-toggle]').count(), 0, 'Watch catalog omits the redundant brand strip');
  await page.screenshot({ path: resolve(output, 'qa-brand-desktop.png') });
  const allCount = await page.locator('#result-count').innerText();
  assert.ok(Number(allCount.split(' ')[0]) > 0, `The public catalog should show watches: ${allCount}`);
  assert.equal(await page.locator('[data-filter="brand"] option[value="super-clone-rolex"]').count(), 1);
  assert.equal(await page.locator('[data-filter="brand"] option[value="richard-mille-highgrade"]').count(), 1);
  await page.goto(base + '/watches/super-clone-rolex');
  await page.locator('.watch-card').first().waitFor({ timeout: 30000 });
  assert.ok(Number((await page.locator('#result-count').innerText()).split(' ')[0]) > 0);
  await page.goto(base + '/watches/richard-mille-highgrade');
  await page.locator('.watch-card').first().waitFor({ timeout: 30000 });
  assert.ok(Number((await page.locator('#result-count').innerText()).split(' ')[0]) > 0);
  await page.goto(base + '/watches/vacheron');
  await page.locator('.watch-card').first().waitFor({ timeout: 30000 });
  assert.ok(Number((await page.locator('#result-count').innerText()).split(' ')[0]) >= 9);
  assert.ok((await page.locator('.watch-card .eyebrow').allInnerTexts()).every((name) => name.toLowerCase() === 'vacheron'));
  await page.goto(base + '/watches/bvlgari');
  await page.locator('.watch-card').first().waitFor({ timeout: 30000 });
  assert.match(await page.locator('.page-heading h1').innerText(), /^Bvlgari watches$/);
  assert.equal(await page.locator('[data-filter="brand"]').inputValue(), 'bvlgari');
  await page.locator('[data-filter="brand"]').selectOption('omega');
  await page.waitForURL('**/watches/omega');
  await page.locator('.watch-card').first().waitFor({ timeout: 30000 });
  assert.match(await page.locator('.page-heading h1').innerText(), /^Omega watches$/);
  assert.equal(await page.locator('[data-filter="brand"]').inputValue(), 'omega');
  assert.equal((await page.locator('.watch-card .eyebrow').first().innerText()).toLowerCase(), 'omega');
  await page.locator('[data-clear]').first().click();
  await page.waitForURL('**/watches');
  await page.locator('.watch-card').first().waitFor({ timeout: 30000 });
  assert.equal(await page.locator('.page-heading h1').innerText(), 'Explore the collection');
  assert.equal(await page.locator('[data-filter="brand"]').inputValue(), '');
  await page.goto(base + '/watches');
  await page.locator('.watch-card').first().waitFor({ timeout: 30000 });
  await page.locator('#catalog-search').fill('AP-001');
  assert.match(await page.locator('#result-count').innerText(), /1 watch/);
  assert.doesNotMatch(await page.locator('.watch-card').first().innerText(), /\b\d+ available\b|Only 1 remaining|Availability on request/i);
  await page.goto(base + '/watches/rolex');
  await page.locator('.watch-card').first().waitFor({ timeout: 30000 });
  assert.match(await page.locator('#result-count').innerText(), /\d+ watches?/);
  await page.goto(base + '/watches');
  await page.locator('.watch-card').first().waitFor({ timeout: 30000 });
  const liveCatalog = await page.evaluate(async (endpoint) => (await fetch(endpoint)).json(), catalogEndpoint);
  assert.ok(liveCatalog.sourceWatchCount > 0, 'The source read should retain the watch catalog');
  assert.equal(liveCatalog.sourceWatchCount, liveCatalog.watches.length);
  const realSoldOut = liveCatalog.watches.find((watch) => watch.stock === 0);
  const soldOut = realSoldOut || liveCatalog.watches.find((watch) => watch.id !== 'AP-001');
  assert.ok(soldOut, 'Catalog should include a watch for the sold-out journey');
  if (!realSoldOut) {
    const fixtureCatalog = structuredClone(liveCatalog);
    fixtureCatalog.watches.find((watch) => watch.id === soldOut.id).stock = 0;
    await page.route('**' + catalogEndpoint, (route) => route.fulfill({ json: fixtureCatalog }));
    await page.reload();
    await page.locator('.watch-card').first().waitFor({ timeout: 30000 });
  }
  await page.locator('[data-filter="availability"]').selectOption('soldout');
  assert.ok(Number((await page.locator('#result-count').innerText()).split(' ')[0]) > 0);
  assert.match(await page.locator('.watch-card').first().innerText(), /Sold out/i);
  assert.equal(await page.locator('.watch-card.is-sold-out .image-badge').first().innerText(), 'SOLD OUT');
  assert.match(await page.locator('.watch-card.is-sold-out .soldout-image-message').first().innerText(), /THIS ITEM IS CURRENTLY\s+UNAVAILABLE/i);
  assert.equal(await page.locator('.watch-card.is-sold-out .was-price').first().evaluate((price) => getComputedStyle(price).textDecorationLine), 'line-through');
  await page.locator('[data-clear]').first().click();
  await page.locator('#catalog-sort').selectOption('price-asc');
  const firstPrices = await page.locator('.watch-card .card-bottom strong').allInnerTexts();
  const numericPrices = firstPrices.slice(0, 2).map((value) => Number(value.replace(/[^\d.]/g, '')));
  assert.ok(numericPrices[0] <= numericPrices[1], 'Price sorting should be ascending');
  await page.goto(base + '/watch/AP-001');
  await page.locator('.detail-copy h1').waitFor({ timeout: 30000 });
  assert.match(await page.locator('.detail-copy h1').innerText(), /Royal Oak/i);
  assert.equal(await page.locator('.detail-stock').count(), 0, 'In-stock watch does not show its quantity');
  for (const width of [1440, 1000]) {
    await page.setViewportSize({ width, height: 1000 });
    const columnGap = await page.locator('.specs-grid').evaluate((grid) => {
      const firstValue = grid.children[0].querySelector('dd').getBoundingClientRect();
      const nextLabel = grid.children[1].querySelector('dt').getBoundingClientRect();
      return nextLabel.left - firstValue.right;
    });
    assert.ok(columnGap >= 20, `Specification columns must not collide at ${width}px: ${columnGap}px`);
  }
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.locator('.specs-section').screenshot({ path: resolve(output, 'qa-watch-specs.png') });
  await page.route('**/chat.js', (route) => route.fulfill({ contentType: 'text/javascript', body: 'export async function openChat(products) { window.__chatProducts = products; }' }));
  await page.locator('.inquiry-button').click();
  await page.waitForFunction(() => window.__chatProducts?.length === 1);
  assert.equal(await page.evaluate(() => window.__chatProducts[0].id), 'AP-001');
  assert.match(await page.evaluate(() => window.__chatProducts[0].url), /\/watch\/AP-001$/);
  await page.locator('.favorite-detail').click();
  await page.goto(base + '/favorites');
  await page.locator('.favorite-row').waitFor({ timeout: 30000 });
  await page.reload();
  await page.locator('.favorite-row').waitFor({ timeout: 30000 });
  await page.locator('[data-select]').check();
  assert.equal(await page.locator('[data-inquire-selected]').isEnabled(), true);
  await page.locator('[data-inquire-selected]').click();
  await page.waitForFunction(() => window.__chatProducts?.some((product) => product.id === 'AP-001'));
  await page.goto(`${base}/watch/${soldOut.id}`);
  await page.locator('.detail-copy h1').waitFor({ timeout: 30000 });
  assert.match(await page.locator('.detail-stock').innerText(), /Sold out/i);
  assert.match(await page.locator('.soldout-notice').innerText(), /This item is currently unavailable/i);
  await page.locator('.inquiry-button').click();
  await page.waitForFunction((id) => window.__chatProducts?.some((product) => product.id === id), soldOut.id);
  await page.goto(base + '/contact');
  await page.locator('.contact-method').first().waitFor({ timeout: 30000 });
  assert.equal(await page.locator('a[href="tel:+639755996605"]').count() > 0, true);
  assert.equal(await page.locator('a[href="viber://chat?number=%2B639755996605"]').count() > 0, true);
  await desktop.close();

  const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  const mobilePage = await mobile.newPage();
  mobilePage.on('pageerror', (error) => errors.push(error.message));
  await mobilePage.goto(base + '/', { waitUntil: 'domcontentloaded' });
  await mobilePage.locator('.hero h1').waitFor({ timeout: 30000 });
  assert.equal(await mobilePage.locator('.floating-chat').isVisible(), true);
  assert.equal(await mobilePage.locator('.trust-banner span').count(), 3);
  const size = await mobilePage.evaluate(() => ({ viewport: innerWidth, content: document.documentElement.scrollWidth }));
  assert.ok(size.content <= size.viewport + 1, `Mobile overflow: ${JSON.stringify(size)}`);
  await mobilePage.screenshot({ path: resolve(output, 'qa-mobile.png') });
  await mobilePage.goto(base + '/watches/omega');
  await mobilePage.locator('.watch-card').first().waitFor({ timeout: 30000 });
  assert.equal(await mobilePage.locator('.brand-list-section, [data-brand-toggle]').count(), 0);
  await mobilePage.screenshot({ path: resolve(output, 'qa-brand-mobile.png') });
  await mobilePage.goto(base + '/');
  await mobilePage.locator('[data-menu]').click();
  assert.equal(await mobilePage.locator('#mobile-nav').isVisible(), true);
  await mobilePage.locator('#mobile-nav a[href="/brands"]').click();
  await mobilePage.locator('.brands-page-content .brand-tile').first().waitFor({ timeout: 30000 });
  assert.equal(new URL(mobilePage.url()).pathname, '/brands', 'Mobile Brands menu opens its own page');
  assert.ok((await mobilePage.evaluate(() => document.documentElement.scrollWidth)) <= 390, 'Brands page fits a phone');
  await mobilePage.goto(base + '/watch/AP-001');
  await mobilePage.locator('.mobile-inquiry-bar').waitFor({ timeout: 30000 });
  assert.equal(await mobilePage.locator('.mobile-inquiry-bar').isVisible(), true);
  assert.equal(await mobilePage.locator('.specs-grid').evaluate((grid) => getComputedStyle(grid).gridTemplateColumns.split(' ').length), 1, 'Phone specifications should use one column');
  await mobile.close();
  assert.deepEqual(errors, [], 'No browser JavaScript errors expected');
  console.log(`Browser QA passed: desktop catalog/search/filter/sort/favorites/inquiry, mobile layout/navigation/detail action; sold-out journey used ${realSoldOut ? 'live stock' : 'a clearly labeled test fixture'}.`);
} finally {
  await browser.close();
}
