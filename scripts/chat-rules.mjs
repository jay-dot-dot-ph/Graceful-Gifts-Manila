import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { initializeTestEnvironment, assertFails, assertSucceeds } from '@firebase/rules-unit-testing';
import { doc, getDoc, collection, query, where, orderBy, limit, getDocs, runTransaction, writeBatch, updateDoc, serverTimestamp, setDoc, deleteDoc } from 'firebase/firestore';
import { sendMessage, editMessage } from '../chat/firebase.js';
import { acknowledge, receiptRef, olderReceipts } from '../chat/receipts.js';

const projectId = 'demo-graceful-gifts-manila';
const environment = await initializeTestEnvironment({ projectId, firestore: { host: '127.0.0.1', port: 8080, rules: readFileSync('firestore.rules', 'utf8') } });
const as = (uid, provider = 'password') => environment.authenticatedContext(uid, { firebase: { sign_in_provider: provider } }).firestore();
const owner = as('owner-uid'), admin = as('admin-uid'), staff = as('staff-uid'), otherStaff = as('other-staff-uid');
const customer = as('customer-uid', 'anonymous'), otherCustomer = as('other-customer-uid', 'anonymous');
try {
  await environment.clearFirestore();
  await environment.withSecurityRulesDisabled(async (context) => {
    for (const [uid, role] of [['owner-uid','owner'], ['admin-uid','admin'], ['staff-uid','staff'], ['other-staff-uid','staff']]) {
      await setDoc(doc(context.firestore(), 'staff', uid), { displayName: uid, email: `${uid}@example.com`, role, active: true, createdAt: new Date(), createdBy: 'setup' });
    }
  });
  await assertSucceeds(sendMessage(customer, 'customer-uid', 'customer-uid', 'customer', 'Is this watch available?', [{ id: 'AP-001', name: 'Royal Oak', brand: 'Audemars Piguet', price: 5950, image: '/images/AP-001-test.jpg', url: 'https://graceful-gifts-manila.web.app/watch/AP-001' }], { name: 'Test customer', contact: 'customer@example.com' }));
  assert.equal((await assertSucceeds(getDoc(doc(customer, 'conversations', 'customer-uid')))).data().status, 'new');
  assert.equal((await getDoc(doc(customer, 'conversations', 'customer-uid'))).data().customerName, 'Test customer');
  const firstMessageId = (await getDoc(doc(customer, 'conversations', 'customer-uid'))).data().lastMessageId;
  await assertFails(updateDoc(doc(customer, 'conversations', 'customer-uid', 'messages', firstMessageId), { message: 'Changed without summary', editedAt: serverTimestamp() }));
  await assertFails(updateDoc(doc(customer, 'conversations', 'customer-uid', 'messages', firstMessageId), { senderRole: 'owner', message: 'Tampered', editedAt: serverTimestamp() }));
  await assertFails(updateDoc(doc(owner, 'conversations', 'customer-uid', 'messages', firstMessageId), { message: 'Not my message', editedAt: serverTimestamp() }));
  await assertSucceeds(editMessage(customer, 'customer-uid', firstMessageId, 'customer-uid', 'Is this Royal Oak available?'));
  assert.equal((await getDoc(doc(customer, 'conversations', 'customer-uid'))).data().lastMessage, 'Is this Royal Oak available?');
  assert.ok((await getDoc(doc(customer, 'conversations', 'customer-uid', 'messages', firstMessageId))).data().editedAt);
  const first = { id: firstMessageId, senderUid: 'customer-uid', senderRole: 'customer' };
  await assertFails(updateDoc(doc(owner, 'conversations', 'customer-uid'), { staffReadAt: serverTimestamp() }));
  await assertFails(setDoc(receiptRef(customer, 'customer-uid', firstMessageId), { recipientUid: 'customer-uid', deliveredAt: serverTimestamp(), seenAt: serverTimestamp(), seenByUid: 'customer-uid' }));
  await assertFails(acknowledge(otherStaff, 'customer-uid', first, 'other-staff-uid', true));
  await assertFails(acknowledge(otherCustomer, 'customer-uid', first, 'other-customer-uid', true));
  await assertFails(getDoc(receiptRef(environment.unauthenticatedContext().firestore(), 'customer-uid', firstMessageId)));
  await assertSucceeds(acknowledge(owner, 'customer-uid', first, 'owner-uid'));
  assert.equal((await getDoc(receiptRef(customer, 'customer-uid', firstMessageId))).data().seenAt, undefined);
  await assertSucceeds(acknowledge(owner, 'customer-uid', first, 'owner-uid', true));
  assert.equal((await olderReceipts(customer, 'customer-uid', [first])).get(firstMessageId).seenByUid, 'owner-uid');
  await assertSucceeds(updateDoc(doc(owner, 'conversations', 'customer-uid'), { staffReadAt: serverTimestamp() }));
  await assertFails(getDoc(doc(otherCustomer, 'conversations', 'customer-uid')));
  await assertFails(getDoc(doc(staff, 'conversations', 'customer-uid')));
  await assertSucceeds(getDoc(doc(admin, 'conversations', 'customer-uid')));
  await assertFails(updateDoc(doc(customer, 'conversations', 'customer-uid'), { status: 'resolved' }));
  await assertFails(setDoc(doc(customer, 'staff', 'customer-uid'), { role: 'owner', active: true }));
  await assertFails(sendMessage(customer, 'customer-uid', 'customer-uid', 'customer', 'Second message too fast'));
  const conversation = doc(admin, 'conversations', 'customer-uid');
  const audit = doc(collection(admin, 'auditLogs'));
  await assertSucceeds(runTransaction(admin, async (tx) => {
    const previous = await tx.get(conversation);
    tx.update(conversation, { assignedStaffUid: 'staff-uid', updatedAt: serverTimestamp(), lastAuditId: audit.id });
    tx.set(audit, { action: 'assignment', conversationId: 'customer-uid', actorUid: 'admin-uid', oldValue: previous.data().assignedStaffUid, newValue: 'staff-uid', createdAt: serverTimestamp() });
  }));
  await assertSucceeds(getDoc(doc(staff, 'conversations', 'customer-uid')));
  await assertFails(getDoc(doc(otherStaff, 'conversations', 'customer-uid')));
  await assertSucceeds(getDocs(query(collection(staff, 'conversations'), where('assignedStaffUid', '==', 'staff-uid'), orderBy('lastMessageAt', 'desc'), limit(50))));
  await assertFails(getDocs(query(collection(staff, 'conversations'), orderBy('lastMessageAt', 'desc'), limit(50))));
  await assertFails(updateDoc(doc(staff, 'conversations', 'customer-uid'), { assignedStaffUid: 'other-staff-uid' }));
  const assigned = doc(staff, 'conversations', 'customer-uid');
  const statusAudit = doc(collection(staff, 'auditLogs'));
  await assertSucceeds(runTransaction(staff, async (tx) => {
    const previous = await tx.get(assigned);
    tx.update(assigned, { status: 'open', updatedAt: serverTimestamp(), lastAuditId: statusAudit.id });
    tx.set(statusAudit, { action: 'status', conversationId: 'customer-uid', actorUid: 'staff-uid', oldValue: previous.data().status, newValue: 'open', createdAt: serverTimestamp() });
  }));
  assert.equal((await assertSucceeds(getDoc(doc(owner, 'conversations', 'customer-uid')))).data().status, 'open');
  await assertFails(getDocs(query(collection(staff, 'auditLogs'), orderBy('createdAt', 'desc'))));
  await assertSucceeds(getDocs(query(collection(owner, 'auditLogs'), orderBy('createdAt', 'desc'))));
  await assertSucceeds(sendMessage(staff, 'customer-uid', 'staff-uid', 'staff', 'It is available.'));
  assert.equal((await assertSucceeds(getDoc(doc(customer, 'conversations', 'customer-uid')))).data().lastMessage, 'It is available.');
  const replyId = (await getDoc(doc(customer, 'conversations', 'customer-uid'))).data().lastMessageId;
  await assertSucceeds(editMessage(customer, 'customer-uid', firstMessageId, 'customer-uid', 'Is the Royal Oak available today?'));
  assert.equal((await getDoc(doc(customer, 'conversations', 'customer-uid'))).data().lastMessage, 'It is available.', 'Editing an older message preserves the inbox preview');
  await assertFails(updateDoc(doc(customer, 'conversations', 'customer-uid', 'messages', replyId), { message: 'Not my reply', editedAt: serverTimestamp() }));
  await assertSucceeds(editMessage(staff, 'customer-uid', replyId, 'staff-uid', 'Yes, it is available.'));
  assert.equal((await getDoc(doc(customer, 'conversations', 'customer-uid'))).data().lastMessage, 'Yes, it is available.');
  const staffReply = { id: replyId, senderUid: 'staff-uid', senderRole: 'staff' };
  await assertFails(updateDoc(doc(customer, 'conversations', 'customer-uid'), { customerReadAt: serverTimestamp() }));
  await assertFails(setDoc(receiptRef(staff, 'customer-uid', replyId), { recipientUid: 'staff-uid', deliveredAt: serverTimestamp(), seenAt: serverTimestamp(), seenByUid: 'staff-uid' }));
  await assertSucceeds(acknowledge(customer, 'customer-uid', staffReply, 'customer-uid'));
  await assertSucceeds(acknowledge(customer, 'customer-uid', staffReply, 'customer-uid', true));
  await assertSucceeds(updateDoc(doc(customer, 'conversations', 'customer-uid'), { customerReadAt: serverTimestamp() }));
  await environment.withSecurityRulesDisabled(async (context) => {
    await updateDoc(doc(context.firestore(), 'conversations', 'customer-uid'), { productReferences: [{ id: 'AP-001', name: 'Royal Oak', brand: 'Audemars Piguet', price: 5950, image: '/images/AP-001-test.jpg', url: 'https://graceful-gifts-manila.web.app/watch/AP-001', size: '42mm', stock: 20 }] });
  });
  await new Promise((resolve) => setTimeout(resolve, 3100));
  await assertSucceeds(sendMessage(customer, 'customer-uid', 'customer-uid', 'customer', 'Can I ask about this watch again?'));
  const finalCustomerMessageId = (await getDoc(doc(customer, 'conversations', 'customer-uid'))).data().lastMessageId;
  await assertSucceeds(updateDoc(doc(owner, 'staff', 'staff-uid'), { active: false }));
  await assertFails(editMessage(staff, 'customer-uid', replyId, 'staff-uid', 'Disabled staff edit'));
  await assertFails(sendMessage(staff, 'customer-uid', 'staff-uid', 'staff', 'I should be disabled.'));
  await assertFails(setDoc(doc(staff, 'staff', 'staff-uid', 'pushTokens', 'c'.repeat(40)), { token: 't'.repeat(80), createdAt: serverTimestamp(), updatedAt: serverTimestamp() }));
  await assertFails(acknowledge(staff, 'customer-uid', { id: finalCustomerMessageId, senderUid: 'customer-uid', senderRole: 'customer' }, 'staff-uid', true));
  await assertFails(updateDoc(doc(owner, 'staff', 'owner-uid'), { active: false }));
  await assertFails(updateDoc(doc(admin, 'staff', 'other-staff-uid'), { role: 'admin' }));
  await assertSucceeds(setDoc(doc(owner, 'settings', 'chat'), { staffSoundEnabled: true, updatedAt: serverTimestamp() }));
  await assertSucceeds(getDoc(doc(admin, 'settings', 'chat')));
  await assertSucceeds(getDoc(doc(customer, 'settings', 'chat')));
  await assertSucceeds(updateDoc(doc(owner, 'settings', 'chat'), { storeAvatarUrl: '/images/store-avatar.webp', updatedAt: serverTimestamp() }));
  await assertFails(updateDoc(doc(owner, 'settings', 'chat'), { storeAvatarUrl: 'https://untrusted.example/photo.png', updatedAt: serverTimestamp() }));
  await assertFails(updateDoc(doc(staff, 'settings', 'chat'), { staffSoundEnabled: false }));
  const tokenRef = doc(owner, 'staff', 'owner-uid', 'pushTokens', 'a'.repeat(40));
  await assertSucceeds(setDoc(tokenRef, { token: 't'.repeat(80), createdAt: serverTimestamp(), updatedAt: serverTimestamp() }));
  await assertSucceeds(getDoc(tokenRef));
  await assertFails(getDoc(doc(admin, 'staff', 'owner-uid', 'pushTokens', 'a'.repeat(40))));
  await assertFails(setDoc(doc(customer, 'staff', 'owner-uid', 'pushTokens', 'b'.repeat(40)), { token: 't'.repeat(80), createdAt: serverTimestamp(), updatedAt: serverTimestamp() }));
  await assertFails(updateDoc(tokenRef, { token: 'replaced' }));
  await assertSucceeds(deleteDoc(tokenRef));
  const blocked = doc(admin, 'blockedCustomers', 'customer-uid');
  await assertFails(setDoc(doc(customer, 'blockedCustomers', 'customer-uid'), { blockedAt: serverTimestamp(), blockedBy: 'customer-uid' }));
  await assertFails(setDoc(doc(otherStaff, 'blockedCustomers', 'customer-uid'), { blockedAt: serverTimestamp(), blockedBy: 'other-staff-uid' }));
  const blockBatch = writeBatch(admin);
  blockBatch.set(blocked, { blockedAt: serverTimestamp(), blockedBy: 'admin-uid' });
  blockBatch.set(doc(collection(admin, 'auditLogs')), { action: 'block', conversationId: 'customer-uid', actorUid: 'admin-uid', createdAt: serverTimestamp() });
  await assertSucceeds(blockBatch.commit());
  await assertFails(getDoc(doc(customer, 'conversations', 'customer-uid')));
  await assertFails(sendMessage(customer, 'customer-uid', 'customer-uid', 'customer', 'Blocked visitor message'));
  await assertFails(sendMessage(owner, 'customer-uid', 'owner-uid', 'owner', 'Blocked staff reply'));
  const unblockBatch = writeBatch(admin);
  unblockBatch.delete(blocked);
  unblockBatch.set(doc(collection(admin, 'auditLogs')), { action: 'unblock', conversationId: 'customer-uid', actorUid: 'admin-uid', createdAt: serverTimestamp() });
  await assertSucceeds(unblockBatch.commit());
  await assertSucceeds(getDoc(doc(customer, 'conversations', 'customer-uid')));
  await assertFails(deleteDoc(doc(admin, 'conversations', 'customer-uid')));
  await assertFails(deleteDoc(doc(customer, 'conversations', 'customer-uid', 'messages', finalCustomerMessageId)));
  const ownerConversation = doc(owner, 'conversations', 'customer-uid');
  for (const name of ['messages', 'receipts']) {
    const page = await getDocs(collection(owner, 'conversations', 'customer-uid', name));
    const batch = writeBatch(owner);
    page.docs.forEach((item) => batch.delete(item.ref));
    await assertSucceeds(batch.commit());
  }
  const deleteBatch = writeBatch(owner);
  deleteBatch.delete(ownerConversation);
  deleteBatch.set(doc(collection(owner, 'auditLogs')), { action: 'delete', conversationId: 'customer-uid', actorUid: 'owner-uid', createdAt: serverTimestamp() });
  await assertSucceeds(deleteBatch.commit());
  await environment.withSecurityRulesDisabled(async (context) => {
    assert.equal((await getDoc(doc(context.firestore(), 'conversations', 'customer-uid'))).exists(), false);
  });
  console.log('Firestore rules passed: customer isolation, inquiry, assignment, staff scope, role protection, rate limit, revocation, private push tokens, block, and delete.');
} finally { await environment.cleanup(); }
